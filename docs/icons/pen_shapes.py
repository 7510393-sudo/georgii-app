"""Пишущие предметы для значка «В» (P477): ручка, карандаш, перо.
Рисуются вдоль оси: остриё в (0,0), хвост — в сторону +x; потом ось
поворачивается на `angle` градусов вверх-вправо от острия."""
import math
from PIL import ImageDraw

def _frame(px, tip, angle):
    a = math.radians(angle)
    u = (math.cos(a), -math.sin(a))      # от острия к хвосту
    v = (math.sin(a), math.cos(a))       # поперёк
    def P(x, y):
        return (px(tip[0] + x * u[0] + y * v[0]), px(tip[1] + x * u[1] + y * v[1]))
    return P

def _poly(d, P, pts, fill, outline=None, w=0):
    xy = [P(x, y) for x, y in pts]
    d.polygon(xy, fill=fill)
    if outline:
        d.line(xy + [xy[0]], fill=outline, width=w, joint="curve")

def draw(kind, layer, px, tip, angle):
    d = ImageDraw.Draw(layer)
    P = _frame(px, tip, angle)
    ink = (28, 33, 40, 255)
    w = max(1, px(.5))
    if kind == "ручка":
        # перьевая ручка: перо, чёрная муфта, золотое кольцо, синий корпус
        _poly(d, P, [(0, 0), (7.5, -1.5), (7.5, 1.5)], (214, 178, 96, 255), ink, w)
        d.line([P(0.8, 0), P(6, 0)], fill=ink, width=max(1, px(.35)))
        _poly(d, P, [(7.5, -1.5), (14, -2.1), (14, 2.1), (7.5, 1.5)], ink)
        _poly(d, P, [(14, -2.2), (15.4, -2.2), (15.4, 2.2), (14, 2.2)], (214, 178, 96, 255), ink, w)
        _poly(d, P, [(15.4, -2.6), (35, -2.6), (35, 2.6), (15.4, 2.6)], (47, 74, 107, 255), ink, w)
        _poly(d, P, [(17, -1.7), (33, -1.7), (33, -0.9), (17, -0.9)], (112, 140, 176, 200))
        _poly(d, P, [(26, 2.7), (34, 2.7), (34, 5.4), (26, 4.6)], (214, 178, 96, 255), ink, w)   # клип
    elif kind == "карандаш":
        # жёлтый карандаш: грифель, заточенное дерево, корпус, обойма, ластик
        _poly(d, P, [(0, 0), (4.2, -1.1), (4.2, 1.1)], (58, 53, 48, 255))
        _poly(d, P, [(4.2, -1.1), (9, -2.5), (9, 2.5), (4.2, 1.1)], (236, 208, 160, 255), ink, w)
        _poly(d, P, [(9, -2.5), (31, -2.5), (31, 2.5), (9, 2.5)], (240, 185, 58, 255), ink, w)
        _poly(d, P, [(9, -0.9), (31, -0.9), (31, 0.7), (9, 0.7)], (214, 150, 30, 255))
        _poly(d, P, [(31, -2.5), (34, -2.5), (34, 2.5), (31, 2.5)], (184, 188, 196, 255), ink, w)
        _poly(d, P, [(34, -2.4), (37.5, -2.4), (37.5, 2.4), (34, 2.4)], (217, 140, 140, 255), ink, w)
    elif kind == "перо":
        # гусиное перо: остриё, стержень, лёгкое опахало
        _poly(d, P, [(0, 0), (6, -0.9), (6, 0.9)], ink)
        top, bot = [], []
        for i in range(0, 41):
            t = i / 40
            x = 5 + t * 34
            half = 5.2 * math.sin(math.pi * min(1, t * 1.15)) ** 0.8
            top.append((x, -0.5 - half * 0.45))
            bot.append((x, 0.5 + half * 0.95))
        _poly(d, P, top + bot[::-1], (253, 250, 241, 255), ink, w)
        d.line([P(5, 0), P(40, 0.2)], fill=(120, 108, 92, 255), width=max(1, px(.55)))
        for k in range(8, 38, 4):
            d.line([P(k, 0.4), P(k + 3.2, 3.6)], fill=(214, 204, 186, 255), width=max(1, px(.25)))
            d.line([P(k, -0.3), P(k + 3.2, -3.0)], fill=(214, 204, 186, 255), width=max(1, px(.25)))
