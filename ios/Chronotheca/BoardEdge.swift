import SwiftUI

/// Торец плашки: у календаря и поиска есть толщина, и на ходу её видно.
///
/// Приём старый и отработанный — фаска. Толщину рисуют тремя вещами разом:
/// светлой гранью с той стороны, откуда падает свет; тёмной гранью с
/// противоположной; и градиентом между ними, который показывает, как свет
/// сходит по торцу. Четвёртое — тень, которую торец кладёт на то, что под
/// ним: без неё доска выглядит наклейкой, а не предметом.
///
/// Свет в интерфейсе всегда сверху — так его рисуют со времён первых
/// экранов, и глаз это читает без объяснений. Поэтому верхняя грань торца
/// светлая, нижняя тёмная, независимо от того, откуда плашка приехала
/// (решение P148).
struct BoardEdge: View {

    /// Толщина доски. Отнимать место у содержимого ей не приходится: торец
    /// выступает за край плашки и лежит на книге.
    static let depth: CGFloat = 14

    /// Докуда достаёт тень торца. Стоящую за краем плашку уводят и на
    /// эту длину, чтобы тень не лежала на экране (P192).
    static let shade: CGFloat = 30

    /// Плашка пришла сверху — значит, торец у неё снизу, и тень падает вниз.
    let fromTop: Bool

    var body: some View {
        VStack(spacing: 0) {
            // Верхняя грань: по ней идёт свет.
            Rectangle().fill(Look.boardLit).frame(height: 1)

            Rectangle().fill(
                LinearGradient(colors: [Look.boardFace, Look.boardDeep],
                               startPoint: .top, endPoint: .bottom))

            // Нижняя грань: тень собственного края.
            Rectangle().fill(Look.boardDark).frame(height: 1.5)
        }
        .frame(height: Self.depth)
        // Тень ложится на книгу с той стороны, куда доска идёт.
        .shadow(color: .black.opacity(0.3), radius: 11,
                x: 0, y: fromTop ? 6 : -6)
        .accessibilityHidden(true)
    }
}
