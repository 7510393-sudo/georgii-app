import SwiftUI

/// Просьбы открытой странице «Дня» (P965, `docs/68` §2.2): вернуться на
/// сегодня, встать на план или на дневник, встать на самый верх, открыть
/// снимок, голос или файлы по кнопке над клавиатурой.
///
/// Прежде эти поля лежали в `Shell`, и каждая просьба пересчитывала всё, что
/// смотрит на оболочку, — и картотеку, и нижнюю строку. Теперь их смотрит
/// одна страница: книга дней (`DayPages`), лист (`DayPage`) и его строка
/// вложений (`AttachBar`). В файл ничего не пишется.
final class PageAsks: ObservableObject {

    /// Просьба вернуться на сегодняшний день.
    /// Поднимается кнопкой «Сегодня» внизу; выполняет её сама книга.
    @Published var goHome = false

    /// Кнопка над клавиатурой попросила открыть фото, голос или файлы —
    /// исполняет полоска открытой страницы (P279).
    @Published var keyboardAsk: KeyboardBar.Ask?
    /// Просьба странице встать на план или на дневник (P424): после
    /// перелистывания и из календаря.
    @Published var landing = 0
    var landOnDiary = false

    /// Касание по дневнику будущего дня (P1063): дневника там ещё нет, и
    /// касание заводит новое дело в плане — курсор в нём, клавиатура
    /// выезжает, можно сразу писать или диктовать.
    @Published var newTask = 0

    /// Сколько раз приложение открывали заново — при запуске и после долгой
    /// паузы. Меняется — страница встаёт на самый верх (P346; к концу
    /// записи она больше не едет, P607).
    @Published var freshStart = 0
}
